#!/usr/bin/env node
"use strict";

// Generates the canonical embedded build identity (build-identity.json) and,
// with --emit-module, the release-commitment JS module that pkg compiles INTO
// server.exe (release builds emit it to server\embedded-commitment.js, where
// both the literal require in server/buildIdentity.js and the pkg.scripts glob
// "server/**/*.js" guarantee inclusion). Both must run BEFORE packaging: the
// module's identityHash covers only the immutable release identity (never the
// exe hash, which would be circular); scripts/bind-executable.js adds the
// measured exe binding to the sidecar AFTER packaging. Re-runs the release
// preflight internally so a tree that changed between the preflight gate and
// identity generation fails closed. Output bytes are canonical: sorted keys,
// compact separators, trailing newline.

const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const { runPreflight } = require("./lib/provenance-preflight");
const {
  canonicalBytes,
  computeIdentityHash,
  validateEmbeddedIdentity,
  IDENTITY_SCHEMA_VERSION,
  WIRE_CONTRACT_ADVISORY,
} = require("../server/buildIdentity");
const {
  assertSafePayloadRelPath,
  resolveNoFollowOutputPath,
} = require("./lib/manifests");

function argValue(flag) {
  const index = process.argv.indexOf(flag);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function argValues(flag) {
  const values = [];
  for (let i = 2; i < process.argv.length; i += 1) {
    if (process.argv[i] === flag) values.push(process.argv[i + 1]);
  }
  return values;
}

function npmVersion() {
  // Fixed, non-configurable arguments only; shell is required on Windows
  // because npm is a .cmd shim (Node >= 18.20 refuses direct .cmd spawns).
  return execFileSync("npm --version", { encoding: "utf8", shell: true }).trim();
}

const projectRoot = path.resolve(
  argValue("--project-root") || path.join(__dirname, ".."),
);
const outPath = path.resolve(argValue("--out") || path.join(projectRoot, "dist", "build-identity.json"));
const emitModulePath = argValue("--emit-module")
  ? path.resolve(argValue("--emit-module"))
  : null;

try {
  const preflight = runPreflight({ projectRoot });
  const outRel = assertSafePayloadRelPath(
    path.relative(projectRoot, outPath).split(path.sep).join("/"),
  );
  const verifiedOutPath = resolveNoFollowOutputPath(projectRoot, outRel).absolutePath;
  const emitModuleRel = emitModulePath === null
    ? null
    : assertSafePayloadRelPath(
      path.relative(projectRoot, emitModulePath).split(path.sep).join("/"),
    );
  const verifiedEmitModulePath = emitModuleRel === null
    ? null
    : resolveNoFollowOutputPath(projectRoot, emitModuleRel).absolutePath;

  const tools = {
    node: process.version,
    npm: npmVersion(),
  };
  for (const pair of argValues("--tool")) {
    const eq = pair.indexOf("=");
    if (eq <= 0) throw new Error(`--tool expects name=value, got "${pair}"`);
    tools[pair.slice(0, eq).trim()] = pair.slice(eq + 1).trim();
  }
  for (const required of ["pkg", "pyinstaller"]) {
    if (!tools[required]) throw new Error(`missing required tool version: ${required}`);
  }

  const identity = {
    schemaVersion: IDENTITY_SCHEMA_VERSION,
    name: "rb-output",
    productVersion: preflight.productVersion,
    releaseTag: preflight.tag,
    gitCommit: preflight.commit,
    gitTree: preflight.tree,
    dirty: false,
    packageLockHash: preflight.packageLockHash,
    generatedAtUtc: new Date().toISOString(),
    wireContracts: WIRE_CONTRACT_ADVISORY,
    tools,
  };
  const verdict = validateEmbeddedIdentity(identity);
  if (!verdict.ok) {
    throw new Error(`generated identity failed self-validation:\n- ${verdict.errors.join("\n- ")}`);
  }

  fs.writeFileSync(verifiedOutPath, canonicalBytes(identity));
  console.log(`build identity written: ${verifiedOutPath}`);
  const identityHash = computeIdentityHash(identity);
  console.log(`identityHash: ${identityHash}`);

  if (verifiedEmitModulePath) {
    // The module is plain source so pkg statically bundles it into server.exe.
    // It commits to the release identity ONLY; the packaged exe hash is bound
    // separately in the sidecar to keep the scheme free of circular hashes.
    const moduleSource = `"use strict";

// GENERATED by scripts/generate-build-identity.js --emit-module. Compiled into
// server.exe before packaging; identifies the immutable release identity this
// executable was built from. Do not edit, reformat, or hand-generate.
const EMBEDDED_RELEASE_COMMITMENT = Object.freeze({
  schemaVersion: ${IDENTITY_SCHEMA_VERSION},
  kind: "rb-output-release-commitment/v1",
  identityHash: "${identityHash}",
});

module.exports = { EMBEDDED_RELEASE_COMMITMENT };
`;
    fs.writeFileSync(verifiedEmitModulePath, moduleSource);
    console.log(`embedded commitment module written: ${verifiedEmitModulePath}`);
  }
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
